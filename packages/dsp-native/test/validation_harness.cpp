// Phase 1 validation harness: runs YIN and MPM head-to-head against
// synthetic fixtures (exact ground truth) and real University-of-Iowa
// violin recordings (plausibility/stability, no exact ground truth), plus
// (if present) the user's own violin recordings under fixtures/user-violin.
// See ../CLAUDE.md for the full write-up of what this measures and why,
// and ../RESULTS.md for the primary-algorithm decision this run produced.
//
// Usage: dsp_native_validation_harness <path-to-test-dir>
//   <path-to-test-dir> is expected to contain fixtures/synthetic
//   (manifest.csv + wavs, generated by generate_synthetic_fixtures),
//   fixtures/iowa (wavs downloaded from the University of Iowa MIS), and
//   fixtures/user-violin (pending — see its own README).
//
// Writes CSVs to <test-dir>/results/ and prints a human-readable summary to
// stdout (also duplicated to <test-dir>/results/summary.txt).

